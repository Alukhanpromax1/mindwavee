// Simulated demonstration trials.
//   Great Bloom:  Ready → Imagery period → Simulated signal → Simulated classification → Visual response
//   Star Altar:   the same sequence with a LEFT / RIGHT cue (optional research illustration)
// The classification outcome comes ONLY from the presenter demo settings — never from the
// player's movement, button presses or any physiological signal.
import { SimulatedSignal, simulateFocusOutcome, simulateLeftRight } from '../simulation/simulatedSignal.js';
import { SIM_LABEL } from '../content/text.js';

const $ = (s) => document.querySelector(s);
const STEPS = ['Ready', 'Imagery period', 'Simulated signal', 'Simulated classification', 'Visual response'];
const HAND = (side) =>
  `<svg viewBox="0 0 48 48" aria-hidden="true" style="transform:${side === 'right' ? 'scaleX(-1)' : 'none'}"><path d="M30 40H18c-4 0-7-3-8-7l-3-10c-.5-1.6 1.6-2.6 2.6-1.3L14 27V9a2 2 0 0 1 4 0v12V6a2 2 0 0 1 4 0v15V8a2 2 0 0 1 4 0v14V11a2 2 0 0 1 4 0v18c0 6-1 11 0 11z"/></svg>`;

export class TrialController {
  constructor(game) {
    this.game = game;
    this.kind = null;
    this.phase = -1;
    this.t = 0;
    this.signal = new SimulatedSignal(3);
    this.canvas = $('#trial-canvas');
    this.result = null;
    this.waitingPresenter = false;
  }

  get active() {
    return this.kind !== null;
  }

  start(kind) {
    const g = this.game;
    this.kind = kind;
    const site = kind === 'bloom' ? g.lm.bloom : g.lm.constellation;
    g.rig.setFocus({ target: site.focusPoint, from: site.cameraFrom });
    g.setState('trial');
    $('#trial-eyebrow').textContent = kind === 'bloom' ? 'The Great Bloom · demonstration trial' : 'Constellation Hollow · experimental';
    $('#trial-title').textContent = kind === 'bloom' ? 'Could a thought become feedback?' : 'Left or right? A research experiment';
    g.ui.show('trial-ui', true);
    this.setPhase(0);
  }

  setPhase(i) {
    this.phase = i;
    this.t = 0;
    this.waitingPresenter = false;
    $('#trial-steps').innerHTML = STEPS.map((s, k) => `<li class="${k < i ? 'is-done' : k === i ? 'is-now' : ''}" ${k === i ? 'aria-current="step"' : ''}>${s}</li>`).join('');
    $('#trial-breath').classList.toggle('is-on', i === 1);
    this.canvas.classList.toggle('is-on', i === 2);
    $('#trial-classifier').classList.toggle('is-on', i === 3 || i === 4);
    const body = $('#trial-body');
    const actions = $('#trial-actions');
    actions.innerHTML = '';
    const g = this.game;
    const isLR = this.kind === 'lr';

    if (i === 0) {
      if (isLR) {
        this.cue = Math.random() < 0.5 ? 'left' : 'right';
        body.innerHTML = `<p class="big">Your cue:</p><div class="cue">${HAND(this.cue)}<span>Imagine moving your <strong>${this.cue.toUpperCase()}</strong> hand</span></div>
          <p>This corner explores imagined left- vs right-hand movement — the task in our preliminary offline analysis. It is experimental and optional.</p>`;
        g.lm.constellation[this.cue].cue = 1;
      } else {
        const n = g.progress.bloomStage;
        const total = g.settings.get('trialsToBloom');
        body.innerHTML = `<p class="big">Get comfortable.</p><p>When you’re ready, begin. A short imagery period follows — there is no right or wrong, and no rush.</p><p class="muted" style="font-size:0.85rem">Bloom: ${Math.min(n, total)} of ${total} simulated responses.</p>`;
      }
      this.button(isLR ? 'Begin experiment' : 'Begin trial', 'primary', () => this.setPhase(1));
      this.button('Step back', 'ghost', () => this.exit());
    } else if (i === 1) {
      body.innerHTML = isLR
        ? `<p class="big">Imagine moving your ${this.cue} hand.</p><p>In a real system, EEG would be recorded during this period. <strong>Here, nothing is recorded.</strong></p>`
        : `<p class="big">Imagine the movement.</p><p>For example, gently opening and closing one hand. In a real system, EEG would be recorded during this period. <strong>Here, nothing is recorded.</strong></p>`;
      this.duration = Math.max(3, g.settings.get('focusDuration') + 1);
      this.button('Step back', 'ghost', () => this.exit());
    } else if (i === 2) {
      body.innerHTML = `<p>A real system would now check signal quality, filter the recording and extract features.</p><p class="muted" style="font-size:0.85rem">${SIM_LABEL} The waveform is generated by the app for illustration.</p>`;
      this.duration = 2.8;
    } else if (i === 3) {
      this.renderClassify();
    } else if (i === 4) {
      this.respond();
    }
  }

  button(label, kind, fn) {
    const b = document.createElement('button');
    b.type = 'button';
    b.className = `btn btn-${kind}${kind === 'primary' ? '' : ' btn-sm'}`;
    b.textContent = label;
    b.addEventListener('click', fn);
    $('#trial-actions').appendChild(b);
    if (kind === 'primary') setTimeout(() => b.focus({ preventScroll: true }), 50);
    return b;
  }

  renderClassify() {
    const g = this.game;
    const body = $('#trial-body');
    const cls = $('#trial-classifier');
    const isLR = this.kind === 'lr';
    const mode = isLR ? g.settings.get('lrMode') : g.settings.get('simOutcome');
    if (mode === 'ask') {
      this.waitingPresenter = true;
      body.innerHTML = `<p><strong>Presenter demo control.</strong> Choose what the simulated classifier reports for this trial.</p>`;
      cls.innerHTML = '';
      if (isLR) {
        this.button('Simulate “left”', 'secondary', () => this.classify('left'));
        this.button('Simulate “right”', 'secondary', () => this.classify('right'));
      } else {
        this.button('Simulate a detection', 'secondary', () => this.classify(true));
        this.button('Simulate no detection', 'secondary', () => this.classify(false));
      }
      return;
    }
    this.classify(null);
  }

  classify(choice) {
    const g = this.game;
    const isLR = this.kind === 'lr';
    this.waitingPresenter = false;
    $('#trial-actions').innerHTML = '';
    const body = $('#trial-body');
    const cls = $('#trial-classifier');
    if (isLR) {
      this.result = simulateLeftRight(g.settings.get('lrMode'), this.cue, choice);
      const c = this.result.confidence;
      const l = this.result.output === 'left' ? c : 1 - c;
      body.innerHTML = `<p>Simulated classifier output <span class="tag-sim">SIMULATED</span></p>`;
      cls.innerHTML = `<div class="bar-row"><span>Left</span><div class="bar"><span style="width:0%" data-w="${l * 100}"></span></div><span>${l.toFixed(2)}</span></div>
        <div class="bar-row"><span>Right</span><div class="bar"><span style="width:0%" data-w="${(1 - l) * 100}"></span></div><span>${(1 - l).toFixed(2)}</span></div>
        <p class="muted" style="font-size:0.8rem;margin:0.3rem 0 0">Illustrative values. ${g.settings.get('lrMode') === 'nearChance' ? 'Outputs match the cue at random 57.6% of the time, mirroring the mean of our adult offline analysis — this is not our model running.' : 'Output chosen by the presenter.'}</p>`;
    } else {
      this.result = simulateFocusOutcome(g.settings.get('simOutcome'), choice);
      const c = this.result.confidence;
      body.innerHTML = `<p>Simulated classifier output <span class="tag-sim">SIMULATED</span></p>`;
      cls.innerHTML = `<div class="bar-row"><span>Imagery</span><div class="bar"><span style="width:0%" data-w="${c * 100}"></span></div><span>${c.toFixed(2)}</span></div>
        <div class="bar-row"><span>Rest</span><div class="bar"><span style="width:0%" data-w="${(1 - c) * 100}"></span></div><span>${(1 - c).toFixed(2)}</span></div>
        <p class="muted" style="font-size:0.8rem;margin:0.3rem 0 0">Illustrative confidence. Outcome set by the demo setting “${{ detect: 'always simulate a detection', ask: 'presenter chooses', random: 'random demo value' }[g.settings.get('simOutcome')]}”.</p>`;
    }
    requestAnimationFrame(() => cls.querySelectorAll('[data-w]').forEach((s) => (s.style.width = `${s.dataset.w}%`)));
    this.duration = 2.2;
  }

  respond() {
    const g = this.game;
    const body = $('#trial-body');
    const isLR = this.kind === 'lr';
    g.stats.sinceRest++;
    if (isLR) {
      const r = this.result;
      g.stats.lrTrials++;
      if (r.matches) g.stats.lrMatches++;
      const C = g.lm.constellation;
      C.left.cue = 0;
      C.right.cue = 0;
      C[r.output].target = Math.min(1, C[r.output].target + 0.35);
      g.fx.sparkles.emit(C[r.output].group.getWorldPosition(C.position.clone()), 40, { spread: 4, up: 1, speed: 1.2 });
      g.audio.chime(r.output === 'left' ? 2 : 4);
      body.innerHTML = `<p class="big">The ${r.output} constellation brightens.</p>
        <p>${r.matches ? 'The simulated output matched the cue.' : 'The simulated output did not match the cue — close to chance, this happens often.'}</p>
        <p class="muted" style="font-size:0.85rem">Simulated outputs matching the cue so far: ${g.stats.lrMatches} of ${g.stats.lrTrials} (illustrative).</p>`;
      if (g.stats.lrTrials >= 3 && !g.progress.star) {
        g.progress.star = true;
        g.onStar();
        body.innerHTML += `<p class="callout callout-teal">You found the optional star fragment. This is why Focus Mode is the default here: near-chance left/right results would make feedback unreliable. Left/right remains a research direction.</p>`;
      }
      this.button('Another experiment', 'primary', () => this.setPhase(0));
      this.button('Why Focus Mode?', 'secondary', () => {
        this.exit();
        g.openSheet('research');
      });
      this.button('Step back', 'ghost', () => this.exit());
      return;
    }
    g.stats.trials++;
    const r = this.result;
    const total = g.settings.get('trialsToBloom');
    if (r.detected) {
      g.stats.detections++;
      const before = g.progress.bloomStage;
      g.progress.bloomStage = Math.min(total, before + 1);
      g.onBloomDetection();
      body.innerHTML =
        g.progress.bloomStage >= total && before < total
          ? `<p class="big">The Great Bloom opens fully.</p><p>A light rises from its heart to join you. Carry it to the Sanctuary.</p>`
          : `<p class="big">The Great Bloom opens a little more.</p><p>Light flows through the basin. (${g.progress.bloomStage} of ${total})</p>`;
    } else {
      g.stats.nonDetections++;
      g.audio.chime(0, 0, 0.08);
      body.innerHTML = `<p class="big">Let’s try another moment.</p><p>The world will wait. Take your time — nothing is lost.</p>`;
    }
    this.button(g.progress.bloomStage >= total ? 'Another trial (optional)' : 'Another trial', 'primary', () => this.setPhase(0));
    this.button('Step back', 'ghost', () => this.exit(true));
  }

  update(dt) {
    if (!this.kind) return;
    this.t += dt;
    if (this.phase === 1) {
      if (this.t >= this.duration) this.setPhase(2);
    } else if (this.phase === 2) {
      this.signal.draw(this.canvas, { time: this.t, filtered: this.t > 1.4, label: 'SIMULATED · NO EEG DATA' });
      if (this.t >= this.duration) this.setPhase(3);
    } else if (this.phase === 3 && !this.waitingPresenter) {
      if (this.t >= this.duration) this.setPhase(4);
    }
  }

  exit(afterResponse = false) {
    const g = this.game;
    if (!this.kind) return;
    if (this.kind === 'lr') {
      g.lm.constellation.left.cue = 0;
      g.lm.constellation.right.cue = 0;
    }
    this.kind = null;
    this.phase = -1;
    g.ui.show('trial-ui', false);
    g.rig.setFocus(null);
    if (g.state === 'trial') g.setState('play');
    if (afterResponse || g.stats.sinceRest > 0) g.checkRest();
  }
}
