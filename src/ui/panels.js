// ================================================================== Map
let mapImage = null;
const MAP = { cx: -10, cz: -10, half: 420, res: 210 };

function buildMapImage() {
  const c = document.createElement('canvas');
  c.width = c.height = MAP.res;
  const g = c.getContext('2d');
  const img = g.createImageData(MAP.res, MAP.res);
  const s = createSample();
  const cols = [
    [183, 215, 122],
    [111, 174, 140],
    [150, 208, 160],
    [207, 220, 127],
    [196, 229, 189],
    [95, 143, 143],
    [169, 207, 134],
  ];
  const step = (MAP.half * 2) / MAP.res;
  const H = new Float32Array(MAP.res * MAP.res);
  for (let j = 0; j < MAP.res; j++) {
    for (let i = 0; i < MAP.res; i++) {
      const x = MAP.cx - MAP.half + i * step;
      const z = MAP.cz - MAP.half + j * step;
      sampleTerrain(x, z, s);
      H[j * MAP.res + i] = s.h;
      let r = 0;
      let gg = 0;
      let b = 0;
      for (let k = 0; k < 7; k++) {
        r += cols[k][0] * s.w[k];
        gg += cols[k][1] * s.w[k];
        b += cols[k][2] * s.w[k];
      }
      if (s.h < WATER_LEVEL) {
        r = 128;
        gg = 202;
        b = 192;
      }
      if (s.path > 0.3 && s.h > 0) {
        r = r * 0.3 + 245 * 0.7;
        gg = gg * 0.3 + 238 * 0.7;
        b = b * 0.3 + 214 * 0.7;
      }
      const k4 = (j * MAP.res + i) * 4;
      img.data[k4] = r;
      img.data[k4 + 1] = gg;
      img.data[k4 + 2] = b;
      img.data[k4 + 3] = 255;
    }
  }
  // hillshade
  for (let j = 1; j < MAP.res - 1; j++) {
    for (let i = 1; i < MAP.res - 1; i++) {
      const k = j * MAP.res + i;
      if (H[k] < 0) continue;
      const dx = H[k + 1] - H[k - 1];
      const dz = H[k + MAP.res] - H[k - MAP.res];
      const shade = Math.max(-0.25, Math.min(0.25, (-dx - dz) * 0.04));
      const k4 = k * 4;
      for (let c2 = 0; c2 < 3; c2++) img.data[k4 + c2] = Math.max(0, Math.min(255, img.data[k4 + c2] * (1 + shade)));
    }
  }
  g.putImageData(img, 0, 0);
  return c;
}

const toMap = (x, z, W) => [((x - (MAP.cx - MAP.half)) / (MAP.half * 2)) * W, ((z - (MAP.cz - MAP.half)) / (MAP.half * 2)) * W];

export function drawMap(canvas, game) {
  if (!mapImage) mapImage = buildMapImage();
  const dpr = Math.min(2, window.devicePixelRatio || 1);
  const W = canvas.clientWidth;
  canvas.width = canvas.height = Math.round(W * dpr);
  const g = canvas.getContext('2d');
  g.setTransform(dpr, 0, 0, dpr, 0, 0);
  g.imageSmoothingEnabled = true;
  g.drawImage(mapImage, 0, 0, W, W);
  const p = game.progress;
  // region labels
  g.textAlign = 'center';
  REGIONS.forEach((r) => {
    if (r.index === R_WILDS) return;
    const [mx, my] = toMap(r.center[0], r.center[1], W);
    g.font = `600 ${Math.max(11, W / 44)}px "Fraunces Variable", Georgia, serif`;
    g.fillStyle = 'rgba(15,59,58,0.85)';
    g.strokeStyle = 'rgba(251,248,237,0.9)';
    g.lineWidth = 4;
    const name = REGION_TEXT[r.id].name.replace('The ', '');
    g.strokeText(name, mx, my - 14);
    g.fillText(name, mx, my - 14);
  });
  // sites
  const site = (id, s, color) => {
    const [mx, my] = toMap(s.x, s.z, W);
    g.beginPath();
    g.arc(mx, my, p.discovered.has(id) ? 5 : 3.5, 0, Math.PI * 2);
    g.fillStyle = p.discovered.has(id) ? color : 'rgba(15,59,58,0.35)';
    g.fill();
    g.strokeStyle = '#fbf8ed';
    g.lineWidth = 1.5;
    g.stroke();
  };
  ['dawnSeed', 'calibration', 'groveTree', 'spring', 'quality', 'features', 'classification', 'feedback', 'greatBloom', 'heart', 'restStones', 'guardian', 'starAltar'].forEach((id) => site(id, SITES[id], '#1f6f68'));
  for (const id of p.hidden) {
    const [, cx, cz] = id.split('_').map(Number);
    const [mx, my] = toMap(cx * 64 + 32, cz * 64 + 32, W);
    g.beginPath();
    g.arc(mx, my, 3, 0, Math.PI * 2);
    g.fillStyle = '#a58fd6';
    g.fill();
  }
  // objective
  const obj = game.currentObjective();
  if (obj?.target) {
    const [ox, oy] = toMap(obj.target.x, obj.target.z, W);
    g.beginPath();
    g.arc(ox, oy, 11, 0, Math.PI * 2);
    g.strokeStyle = '#d6a03c';
    g.lineWidth = 3;
    g.stroke();
  }
  // player
  const pl = game.player.pos;
  const [px, py] = toMap(pl.x, pl.z, W);
  g.save();
  g.translate(px, py);
  g.rotate(-game.player.heading + Math.PI);
  g.beginPath();
  g.moveTo(0, -10);
  g.lineTo(7, 8);
  g.lineTo(0, 4);
  g.lineTo(-7, 8);
  g.closePath();
  g.fillStyle = '#0f3b3a';
  g.fill();
  g.strokeStyle = '#fbf8ed';
  g.lineWidth = 2;
  g.stroke();
  g.restore();
}

