export function renderSettings(body, settings) {
  const html = SETTING_DEFS.map((d) => {
    if (d[0] === 'section') return `<h4 class="settings-section">${esc(d[1])}</h4>`;
    if (d[0] === 'toggle') return `<label class="toggle"><input type="checkbox" data-toggle="${d[1]}" ${settings.get(d[1]) ? 'checked' : ''}/> ${esc(d[2])}</label>`;
    const [key, label, help] = d;
    const opts = OPTIONS[key].map(([v, l]) => `<option value="${esc(v)}" ${String(settings.get(key)) === String(v) ? 'selected' : ''}>${esc(l)}</option>`).join('');
    return `<div class="setting"><label for="set-${key}">${esc(label)}</label><select id="set-${key}" data-select="${key}">${opts}</select>${help ? `<small>${esc(help)}</small>` : ''}</div>`;
  }).join('');
  body.innerHTML = `<div class="settings-grid">${html}</div><div class="actions"><button class="btn btn-ghost" id="settings-reset" type="button">Restore defaults</button></div>
  <p class="muted" style="font-size:0.85rem">Settings are stored only in this browser. MindWave collects no personal, health or neural data.</p>`;
  body.querySelectorAll('[data-select]').forEach((el) =>
    el.addEventListener('change', () => {
      const key = el.dataset.select;
      const raw = el.value;
      const sample = OPTIONS[key][0][0];
      settings.set(key, typeof sample === 'number' ? Number(raw) : raw);
    })
  );
  body.querySelectorAll('[data-toggle]').forEach((el) => el.addEventListener('change', () => settings.set(el.dataset.toggle, el.checked)));
  body.querySelector('#settings-reset').addEventListener('click', () => {
    settings.reset();
    renderSettings(body, settings);
  });
}

